#!/bin/bash -e

scriptFileName="${BASH_SOURCE[0]}"
if [[ -L "${scriptFileName}" ]] && [[ -x "$(command -v readlink)" ]]; then
  scriptFileName=$(readlink -f "${scriptFileName}")
fi

usage()
{
cat >&2 << EOF

Creates a Magento 2.4 project from repo.magento.com (or installs the dependencies of an existing project) and installs
Magento into an empty database with setup:install. If the project is already installed (app/etc/env.php exists), only
the admin user is created. To attach the project to an existing database instead, use: cosyses Magento env.sh
PHP with the Magento modules (cosyses PHP <version> magento.sh), Composer, the database and the search engine have to be
installed and running, the database and its user have to exist (e.g. cosyses MariaDB <version> create-user.sh).

usage: ${scriptFileName} options

OPTIONS:
  --help               Show this message
  --appPath            Path of the project, default: /var/www/magento/htdocs
  --user               System user who owns the project and runs Composer and bin/magento, default: www-data
  --magentoVersion     Version or constraint of the project package, default: 2.4.*
  --magentoEdition     community or enterprise, default: community
  --composerUser       Public key of repo.magento.com (stored with cosyses Composer auth.sh, optional if stored already)
  --composerPassword   Private key of repo.magento.com
  --securityBlocking   Let Composer refuse package versions with security advisories (yes/no), default: yes
  --hideDeprecations   Hide deprecation messages in app/bootstrap.php (yes/no), default: yes
  --baseUrl            Base URL of the shop, default: https://localhost/
  --adminPath          Path of the admin area, default: admin
  --adminUser          Admin user name, default: admin
  --adminPassword      Admin password, default: <generated>
  --adminFirstName     Admin first name, default: Admin
  --adminLastName      Admin last name, default: User
  --adminEmail         Admin email address, default: admin@example.com
  --databaseHost       Database host, default: localhost
  --databasePort       Database port, default: 3306
  --databaseUser       Database user
  --databasePassword   Database password
  --databaseName       Database name, default: magento
  --searchEngine       opensearch, elasticsearch7 or elasticsearch8, default: opensearch
  --searchHost         Search engine host, default: localhost
  --searchPort         Search engine port, default: 9200
  --queueHost          RabbitMQ host (AMQP is only configured if a queue user is given), default: localhost
  --queuePort          RabbitMQ port, default: 5672
  --queueUser          RabbitMQ user
  --queuePassword      RabbitMQ password
  --queueVirtualHost   RabbitMQ virtual host, default: /
  --queueSsl           Use SSL for RabbitMQ (true/false), default: false
  --locale             Locale, default: en_US
  --currency           Currency, default: USD
  --timezone           Time zone, default: UTC
  --cryptKey           Encryption key (32 characters), default: <generated by Magento>

Example: ${scriptFileName} --magentoVersion 2.4.8-p3 --composerUser <public key> --composerPassword <private key> --baseUrl https://shop.local/ --databaseUser magento --databasePassword secret --adminPassword secret123
EOF
}

if [[ -z "${cosysesPath}" ]]; then
  >&2 echo "No cosyses path exported!"
  echo ""
  exit 1
fi

appPath=
user=
magentoVersion=
magentoEdition=
composerUser=
composerPassword=
securityBlocking=
hideDeprecations=
baseUrl=
adminPath=
adminUser=
adminPassword=
adminFirstName=
adminLastName=
adminEmail=
databaseHost=
databasePort=
databaseUser=
databasePassword=
databaseName=
searchEngine=
searchHost=
searchPort=
queueHost=
queuePort=
queueUser=
queuePassword=
queueVirtualHost=
queueSsl=
locale=
currency=
timezone=
cryptKey=
source "${cosysesPath}/prepare-parameters.sh"

if [[ -z "${appPath}" ]]; then
  appPath="/var/www/magento/htdocs"
fi

if [[ -z "${user}" ]]; then
  user="www-data"
fi

if [[ -z "${magentoVersion}" ]]; then
  magentoVersion="2.4.*"
fi

if [[ -z "${magentoEdition}" ]]; then
  magentoEdition="community"
fi

if [[ "${magentoEdition}" != "community" ]] && [[ "${magentoEdition}" != "enterprise" ]]; then
  >&2 echo "Invalid Magento edition: ${magentoEdition}, use community or enterprise"
  usage
  exit 1
fi

if [[ -z "${securityBlocking}" ]]; then
  securityBlocking="yes"
fi

if [[ -z "${hideDeprecations}" ]]; then
  hideDeprecations="yes"
fi

if [[ -z "${baseUrl}" ]]; then
  baseUrl="https://localhost/"
fi

if [[ "${baseUrl}" != */ ]]; then
  baseUrl="${baseUrl}/"
fi

if [[ -z "${adminPath}" ]]; then
  adminPath="admin"
fi

if [[ -z "${adminUser}" ]]; then
  adminUser="admin"
fi

if [[ -z "${adminPassword}" ]]; then
  # Magento requires letters and digits
  adminPassword="a1$(echo "${RANDOM}${RANDOM}" | md5sum | head -c 14)"
  echo "Using generated admin password: ${adminPassword}"
fi

if [[ -z "${adminFirstName}" ]]; then
  adminFirstName="Admin"
fi

if [[ -z "${adminLastName}" ]]; then
  adminLastName="User"
fi

if [[ -z "${adminEmail}" ]]; then
  adminEmail="admin@example.com"
fi

if [[ -z "${databaseHost}" ]]; then
  databaseHost="localhost"
fi

if [[ -z "${databasePort}" ]]; then
  databasePort="3306"
fi

if [[ -z "${databaseName}" ]]; then
  databaseName="magento"
fi

if [[ -z "${searchEngine}" ]]; then
  searchEngine="opensearch"
fi

case "${searchEngine}" in
  opensearch) searchOptionPrefix="opensearch" ;;
  elasticsearch|elasticsearch7) searchEngine="elasticsearch7"; searchOptionPrefix="elasticsearch" ;;
  elasticsearch8) searchOptionPrefix="elasticsearch" ;;
  *) >&2 echo "Invalid search engine: ${searchEngine}, use opensearch, elasticsearch7 or elasticsearch8"; usage; exit 1 ;;
esac

if [[ -z "${searchHost}" ]]; then
  searchHost="localhost"
fi

if [[ -z "${searchPort}" ]]; then
  searchPort="9200"
fi

if [[ -z "${queueHost}" ]]; then
  queueHost="localhost"
fi

if [[ -z "${queuePort}" ]]; then
  queuePort="5672"
fi

if [[ -z "${queueVirtualHost}" ]]; then
  queueVirtualHost="/"
fi

if [[ -z "${queueSsl}" ]]; then
  queueSsl="false"
fi

if [[ -z "${locale}" ]]; then
  locale="en_US"
fi

if [[ -z "${currency}" ]]; then
  currency="USD"
fi

if [[ -z "${timezone}" ]]; then
  timezone="UTC"
fi

if [[ ! -f "${appPath}/app/etc/env.php" ]]; then
  if [[ -z "${databaseUser}" ]]; then
    >&2 echo "No database user specified!"
    usage
    exit 1
  fi

  if [[ -z "${databasePassword}" ]]; then
    >&2 echo "No database password specified!"
    usage
    exit 1
  fi
fi

if [[ ! -x "$(command -v php)" ]]; then
  >&2 echo "PHP not found, install it first (cosyses PHP <version> magento.sh)"
  exit 1
fi

if [[ ! -x "$(command -v composer)" ]]; then
  >&2 echo "Composer not found, install it first (cosyses Composer <version>)"
  exit 1
fi

if ! id "${user}" > /dev/null 2>&1; then
  >&2 echo "User not found: ${user}"
  exit 1
fi

runAsUser()
{
  if [[ "${user}" != "$(whoami)" ]]; then
    sudo -H -u "${user}" "$@"
  else
    "$@"
  fi
}

runMagento()
{
  runAsUser php "${appPath}/bin/magento" "$@" 2>&1
}

# Composer keeps its configuration and cache in the home directory of the user, which belongs to root for www-data
if [[ "${user}" != "$(whoami)" ]]; then
  userHome=$(getent passwd "${user}" | cut -d: -f6)
  userGroup=$(id -gn "${user}")
  for composerDirectory in "${userHome}/.config" "${userHome}/.config/composer" "${userHome}/.cache" "${userHome}/.cache/composer"; do
    if [[ ! -d "${composerDirectory}" ]]; then
      echo "Creating directory: ${composerDirectory}"
      mkdir -p "${composerDirectory}"
    fi
    if [[ "$(stat -c '%U' "${composerDirectory}")" != "${user}" ]]; then
      chown "${user}:${userGroup}" "${composerDirectory}"
    fi
  done
fi

if [[ -n "${composerUser}" ]] && [[ -n "${composerPassword}" ]]; then
  cosyses \
    --applicationName Composer \
    --applicationScript auth.sh \
    --hostName repo.magento.com \
    --authUser "${composerUser}" \
    --authPassword "${composerPassword}" \
    --user "${user}"
elif [[ ! -f "${appPath}/composer.json" ]]; then
  echo "No keys for repo.magento.com specified, using the stored ones of user: ${user}"
fi

cosyses \
  --applicationName Composer \
  --applicationScript create-project.sh \
  --packageName "magento/project-${magentoEdition}-edition" \
  --packageVersion "${magentoVersion}" \
  --repositoryUrl "https://repo.magento.com/" \
  --appPath "${appPath}" \
  --binaries bin/magento \
  --securityBlocking "${securityBlocking}" \
  --user "${user}"

cd "${appPath}"

if [[ "${hideDeprecations}" == "yes" ]]; then
  # E_STRICT is not used since PHP 8.0 and its constant is deprecated since PHP 8.4
  if grep -q "error_reporting(E_ALL);" app/bootstrap.php; then
    echo "Hiding deprecation messages in: ${appPath}/app/bootstrap.php"
    runAsUser sed -i -e 's/error_reporting(E_ALL);/error_reporting(E_ALL \& ~E_DEPRECATED);/' app/bootstrap.php
  fi
fi

installedVersion=$(runMagento --version | awk '{print $NF}')
echo "Installed Magento version: ${installedVersion}"

if [[ -f "${appPath}/app/etc/env.php" ]]; then
  echo "Magento is already installed, creating admin user: ${adminUser}"
  runMagento admin:user:create \
    "--admin-user=${adminUser}" \
    "--admin-password=${adminPassword}" \
    "--admin-firstname=${adminFirstName}" \
    "--admin-lastname=${adminLastName}" \
    "--admin-email=${adminEmail}"
else
  installArguments=(
    setup:install
    --no-interaction
    "--admin-user=${adminUser}"
    "--admin-password=${adminPassword}"
    "--admin-firstname=${adminFirstName}"
    "--admin-lastname=${adminLastName}"
    "--admin-email=${adminEmail}"
    "--db-host=${databaseHost}:${databasePort}"
    "--db-name=${databaseName}"
    "--db-user=${databaseUser}"
    "--db-password=${databasePassword}"
    "--base-url=${baseUrl}"
    "--backend-frontname=${adminPath}"
    "--language=${locale}"
    "--currency=${currency}"
    "--timezone=${timezone}"
    --session-save=files
    --use-rewrites=1
    "--search-engine=${searchEngine}"
    "--${searchOptionPrefix}-host=${searchHost}"
    "--${searchOptionPrefix}-port=${searchPort}"
  )
  if [[ "${baseUrl}" == https://* ]]; then
    installArguments+=( "--base-url-secure=${baseUrl}" --use-secure=1 --use-secure-admin=1 )
  fi
  if [[ -n "${cryptKey}" ]]; then
    installArguments+=( "--key=${cryptKey}" )
  fi
  if [[ -n "${queueUser}" ]]; then
    installArguments+=(
      "--amqp-host=${queueHost}"
      "--amqp-port=${queuePort}"
      "--amqp-user=${queueUser}"
      "--amqp-password=${queuePassword}"
      "--amqp-virtualhost=${queueVirtualHost}"
      "--amqp-ssl=${queueSsl}"
    )
  fi

  echo "Installing Magento with base URL: ${baseUrl}"
  runMagento "${installArguments[@]}"
fi

runMagento cache:clean
